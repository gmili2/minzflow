/** Pagination côté client des listes. */
export function usePager<T>(rows: T[], size = 12) {
  const [pg, setPg] = useState(1);
  const pages = Math.max(1, Math.ceil(rows.length / size));
  const cur = Math.min(pg, pages);
  useEffect(() => { setPg(1); }, [rows.length]);
  return {
    slice: rows.slice((cur - 1) * size, cur * size),
    bar: rows.length > size ? (
      <div className="pager">
        <span className="muted">{(cur - 1) * size + 1}–{Math.min(cur * size, rows.length)} sur {rows.length}</span>
        <div className="pager-ctrl">
          <button className="mini" disabled={cur <= 1} onClick={() => setPg(cur - 1)} aria-label="Page précédente"><Icon name="left" size={16} /></button>
          <span style={{ padding: '0 8px', fontWeight: 600 }}>{cur} / {pages}</span>
          <button className="mini" disabled={cur >= pages} onClick={() => setPg(cur + 1)} aria-label="Page suivante"><Icon name="right" size={16} /></button>
        </div>
      </div>
    ) : null,
  };
}
