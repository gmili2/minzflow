const ToastCtx = createContext<(msg: string) => void>(() => undefined);
export function ToastProvider({ children }: { children: ReactNode }) {
  const [msg, setMsg] = useState('');
  const t = useRef<number | undefined>(undefined);
  const notify = useCallback((m: string) => {
    setMsg(m); window.clearTimeout(t.current);
    t.current = window.setTimeout(() => setMsg(''), 3200);
  }, []);
  return (
    <ToastCtx.Provider value={notify}>
      {children}
      {msg && <div className="toast" role="status"><Icon name="check" size={18} />{msg}</div>}
    </ToastCtx.Provider>
  );
}
export const useToast = () => useContext(ToastCtx);

/** Chargement d'une ressource : { data, error, loading, reload }. */
export function useData<T>(load: () => Promise<T>, deps: unknown[] = []) {
  const [state, setState] = useState<{ data: T | null; error: string; loading: boolean }>({ data: null, error: '', loading: true });
  const [n, setN] = useState(0);
  useEffect(() => {
    let alive = true;
    setState((s) => ({ ...s, loading: true }));
    load().then((data) => alive && setState({ data, error: '', loading: false }))
      .catch((e: Error) => alive && setState({ data: null, error: e.message, loading: false }));
    return () => { alive = false; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [...deps, n]);
  return { ...state, reload: () => setN((x) => x + 1) };
}

